"""
5×4 tile measurements — reproduce every number and figure in tile_5x4/README.md
  2026-11-21  preliminary sessions (finger-press tests, stepping)
  2026-11-23  cafeteria entrance at lunch, 50 hand-counted crossings

  python tile_results.py        (needs: numpy, matplotlib)

Reads ../piezo_main/piezo_2026xxxx_xxxxxx/ (raw_serial.txt, pulses.csv, status.csv, meta.csv)
Writes ../figures/*.png and results.md (in this folder).
Only measured quantities are reported. Model/assumption-based numbers are kept out of this script.
"""
import csv, os, statistics as st
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
MAIN = os.path.normpath(os.path.join(HERE, "..", "piezo_main"))
FIG = os.path.normpath(os.path.join(HERE, "..", "figures"))
os.makedirs(FIG, exist_ok=True)

SESSIONS = [  # (folder, kind) — kind told by the experimenter, not inferred
    ("piezo_20261121_192827", "finger"),
    ("piezo_20261121_201257", "finger"),
    ("piezo_20261121_202319", "stepping"),
    ("piezo_20261121_203520", "stepping"),
    ("piezo_20261121_205200", "stepping"),
]
LABEL = {"finger": "finger-press function test", "stepping": "stepping on the tile"}


def rows(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return 0.0


def raw_samples(folder):
    """R lines from raw_serial.txt → (t_ms, a1..a4) array"""
    out = []
    with open(os.path.join(folder, "raw_serial.txt"), encoding="utf-8", errors="ignore") as fh:
        for ln in fh:
            if ln.startswith("R,"):
                p = ln.strip().split(",")
                if len(p) == 6:
                    try:
                        out.append([int(v) for v in p[1:]])
                    except ValueError:
                        pass
    return np.array(out, dtype=float)


res = []
for name, kind in SESSIONS:
    d = os.path.join(MAIN, name)
    P, S, M = rows(os.path.join(d, "pulses.csv")), rows(os.path.join(d, "status.csv")), rows(os.path.join(d, "meta.csv"))
    m = M[-1]
    k = f(m["VREF"]) / 1023 * (f(m["R1"]) + f(m["R2"])) / f(m["R2"])
    R = raw_samples(d)
    span_s = (R[-1, 0] - R[0, 0]) / 1000
    E = np.array([sum(f(r[f"r{i}_E_uJ"]) for i in range(1, 5)) for r in P])
    Q = np.array([sum(f(r[f"r{i}_Q_nC"]) for i in range(1, 5)) for r in P])
    peak = np.array([max(f(r[f"r{i}_peak_V"]) for i in range(1, 5)) for r in P])
    nrows = np.array([int(f(r["rows_hit"])) for r in P])
    dur = np.array([f(r["dur_ms"]) for r in P])
    t0 = np.array([f(r["t_start_ms"]) for r in P])
    active_s = (t0[-1] + dur[-1] - t0[0]) / 1000        # first pulse start → last pulse end
    res.append(dict(
        name=name, kind=kind, d=d, k=k, R=R, P=P,
        span_min=span_s / 60, completeness=len(R) / (span_s * 500) * 100,
        dropped=int(f(S[-1]["dropped_samples"])) if S else 0,
        clipped=sum(1 for r in P if any(f(r[f"r{i}_clip"]) for i in range(1, 5))),
        n=len(P), E=E, Q=Q, peak=peak, nrows=nrows, dur=dur, active_s=active_s,
        E_total=E.sum(), P_active=E.sum() / active_s))

# ── results.md
L = ["# 5×4 tile — measured results (auto-generated by tile_results.py)", "",
     "All values come from the files in `../piezo_main/`. Energy = energy delivered to the 1.1 MΩ measuring",
     "resistor per row, computed on the Arduino as Σ V²/R·Δt (2 ms steps); summed over the 4 rows.", "",
     "| session | what was done | recording | raw-sample completeness | pulses | peak V (median / max) | energy per pulse µJ (median / mean / max) | total µJ | active time s | mean power while active µW | rows hit per pulse (1/2/3/4) | clipped |",
     "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in res:
    c = [int((r["nrows"] == j).sum()) for j in (1, 2, 3, 4)]
    L.append(f"| `{r['name'][6:]}` | {LABEL[r['kind']]} | {r['span_min']:.1f} min | {r['completeness']:.1f} % | {r['n']} | "
             f"{np.median(r['peak']):.2f} / {r['peak'].max():.2f} | {np.median(r['E']):.3f} / {r['E'].mean():.3f} / {r['E'].max():.3f} | "
             f"{r['E_total']:.1f} | {r['active_s']:.0f} | {r['P_active']:.2f} | {c[0]}/{c[1]}/{c[2]}/{c[3]} | {r['clipped']} |")
for kind in ("finger", "stepping"):
    E = np.concatenate([r["E"] for r in res if r["kind"] == kind])
    Pk = np.concatenate([r["peak"] for r in res if r["kind"] == kind])
    nr = np.concatenate([r["nrows"] for r in res if r["kind"] == kind])
    Qc = np.concatenate([r["Q"] for r in res if r["kind"] == kind])
    L += ["", f"**All {LABEL[kind]} pulses pooled (n = {len(E)}):** energy per pulse median {np.median(E):.3f} µJ, "
          f"mean {E.mean():.3f} µJ, IQR {np.percentile(E,25):.3f}–{np.percentile(E,75):.3f} µJ; peak voltage median {np.median(Pk):.2f} V; "
          f"charge per pulse median {np.median(Qc)/1000:.3f} µC; pulses with ≥3 rows above threshold: {(nr >= 3).mean()*100:.0f} %."]
fin = np.concatenate([r["E"] for r in res if r["kind"] == "finger"])
stp = np.concatenate([r["E"] for r in res if r["kind"] == "stepping"])
L += ["", f"Median energy per pulse, stepping ÷ finger: **{np.median(stp)/np.median(fin):.1f}×**.", "",
      "Not included: `piezo_20261121_192928` (finger test; a row was pressed during the 2-s noise baseline,",
      "13 corrupted serial lines, 43 min mostly idle)."]
open(os.path.join(HERE, "results.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))

